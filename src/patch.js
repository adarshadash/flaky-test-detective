// Applying a fix, producing a reviewable unified diff, and opening a pull request.
import { copyFile, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { spawnProcess } from './runner.js';

/** Minimal LCS-based unified diff (no dependency, works on Windows too). */
export function unifiedDiff(oldText, newText, { fromFile = 'a', toFile = 'b', context = 3 } = {}) {
  const lines = (t) => (t === '' ? [] : (t.endsWith('\n') ? t.slice(0, -1) : t).split('\n'));
  const a = lines(oldText);
  const b = lines(newText);
  const n = a.length;
  const m = b.length;
  const lcs = Array.from({ length: n + 1 }, () => new Int32Array(m + 1));
  for (let i = n - 1; i >= 0; i--) for (let j = m - 1; j >= 0; j--) lcs[i][j] = a[i] === b[j] ? lcs[i + 1][j + 1] + 1 : Math.max(lcs[i + 1][j], lcs[i][j + 1]);

  const ops = []; // {t:' '|'-'|'+', line, ai, bi}
  let i = 0;
  let j = 0;
  while (i < n || j < m) {
    if (i < n && j < m && a[i] === b[j]) ops.push({ t: ' ', line: a[i], ai: i++, bi: j++ });
    // deletions before additions, like git
    else if (i < n && (j >= m || lcs[i + 1][j] >= lcs[i][j + 1])) ops.push({ t: '-', line: a[i], ai: i++, bi: j });
    else ops.push({ t: '+', line: b[j], ai: i, bi: j++ });
  }
  if (!ops.some((o) => o.t !== ' ')) return '';

  // Each change pulls in `context` lines on either side; overlapping windows merge.
  const hunks = [];
  ops.forEach((o, idx) => {
    if (o.t === ' ') return;
    const start = Math.max(0, idx - context);
    const end = Math.min(ops.length, idx + context + 1);
    const last = hunks[hunks.length - 1];
    if (last && start <= last.end) last.end = Math.max(last.end, end);
    else hunks.push({ start, end });
  });

  const out = [`--- ${fromFile}`, `+++ ${toFile}`];
  for (const { start, end } of hunks) {
    const slice = ops.slice(start, end);
    const aStart = slice[0].ai + 1;
    const bStart = slice[0].bi + 1;
    const aLen = slice.filter((o) => o.t !== '+').length;
    const bLen = slice.filter((o) => o.t !== '-').length;
    out.push(`@@ -${aLen ? aStart : aStart - 1},${aLen} +${bLen ? bStart : bStart - 1},${bLen} @@`);
    for (const o of slice) out.push(o.t + o.line);
  }
  return out.join('\n') + '\n';
}

/** Write the fixed source, keeping a .ftd-backup copy. Returns the diff. */
export async function applyFix(file, fixedSource) {
  const original = await readFile(file, 'utf8');
  if (original === fixedSource) return { changed: false, diff: '', backup: null };
  const backup = `${file}.ftd-backup`;
  await copyFile(file, backup);
  const written = fixedSource.endsWith('\n') ? fixedSource : fixedSource + '\n';
  await writeFile(file, written);
  const rel = path.basename(file);
  return { changed: true, backup, diff: unifiedDiff(original, written, { fromFile: `a/${rel}`, toFile: `b/${rel}` }) };
}

export async function restoreBackup(file, backup) {
  if (backup) await copyFile(backup, file);
}

export const branchName = (title) =>
  'ftd/fix-' +
  title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 48);

/** Markdown body for the PR, built from the evidence. */
export function prBody({ analysis, heuristic, diagnosis, verification }) {
  const rows = analysis.variations.map((v) => `| ${v.name} | ${v.failures}/${v.runs} | ${Math.round(v.rate * 100)}% |${v.significant ? ' ⚠️ significant' : ''}`).join('\n');
  const after = verification
    ? `\n### Verification\nRe-ran the fixed test under the same variations: **${verification.overall.failures}/${verification.overall.runs} failures** (was ${analysis.overall.failures}/${analysis.overall.runs}).\n`
    : '';
  return `## 🔎 Flaky Test Detective: ${diagnosis?.title || heuristic.label}

**Test:** \`${analysis.title}\` (${analysis.file})
**Root cause:** ${diagnosis?.category || heuristic.cause} — ${diagnosis?.explanation || heuristic.fix}

### Evidence
| variation | failed | rate |
|---|---|---|
${rows}

${(diagnosis?.evidence?.length ? diagnosis.evidence : heuristic.evidence).map((e) => `- ${e}`).join('\n')}
${after}
_Generated by flaky-test-detective._`;
}

/**
 * Commit the fix on a new branch and open a PR with the GitHub CLI.
 * `exec` is injectable for tests. Returns { branch, committed, prUrl, skipped? }.
 */
export async function openPullRequest({ cwd, file, title, body, exec = spawnProcess, push = true }) {
  const git = (...args) => exec('git', args, { cwd });
  const inRepo = await git('rev-parse', '--is-inside-work-tree');
  if (inRepo.code !== 0) return { skipped: 'not a git repository' };

  const branch = branchName(title);
  const co = await git('checkout', '-b', branch);
  if (co.code !== 0) throw new Error(`git checkout failed: ${co.stderr}`);
  await git('add', path.relative(cwd, file));
  const commit = await git('commit', '-m', `test: fix flaky "${title}"`, '-m', 'Root cause and evidence found by flaky-test-detective.');
  if (commit.code !== 0) throw new Error(`git commit failed: ${commit.stderr || commit.stdout}`);
  if (!push) return { branch, committed: true, prUrl: null };

  const remote = await git('remote');
  if (!remote.stdout.trim()) return { branch, committed: true, prUrl: null, skipped: 'no git remote configured' };
  const pushed = await git('push', '-u', 'origin', branch);
  if (pushed.code !== 0) return { branch, committed: true, prUrl: null, skipped: `push failed: ${pushed.stderr.trim()}` };

  const pr = await exec('gh', ['pr', 'create', '--title', `Fix flaky test: ${title}`, '--body', body, '--head', branch], { cwd });
  if (pr.code !== 0) return { branch, committed: true, prUrl: null, skipped: `gh pr create failed: ${pr.stderr.trim()}` };
  return { branch, committed: true, prUrl: pr.stdout.trim().split('\n').pop() };
}
